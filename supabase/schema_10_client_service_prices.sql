-- Персональные цены услуг для отдельных клиентов.
-- Обычная цена остаётся в services.price; фактическая стоимость записи хранится
-- в appointments.price/full_price, а list_price сохраняет цену общего прайса.

create table if not exists public.client_service_prices (
  id bigint generated by default as identity primary key,
  owner_id uuid not null default auth.uid() references auth.users(id) on delete cascade,
  client_id bigint not null references public.clients(id) on delete cascade,
  service_id bigint not null references public.services(id) on delete cascade,
  price integer not null check (price >= 0),
  updated_at timestamptz not null default now(),
  unique (owner_id, client_id, service_id)
);

alter table public.client_service_prices enable row level security;

grant select, insert, update, delete on public.client_service_prices to authenticated;

drop policy if exists "own client service prices" on public.client_service_prices;
create policy "own client service prices"
on public.client_service_prices
for all
to authenticated
using (
  owner_id = (select auth.uid())
  and exists (
    select 1 from public.clients c
    where c.id = client_service_prices.client_id
      and c.owner_id = (select auth.uid())
  )
  and exists (
    select 1 from public.services s
    where s.id = client_service_prices.service_id
      and s.owner_id = (select auth.uid())
  )
)
with check (
  owner_id = (select auth.uid())
  and exists (
    select 1 from public.clients c
    where c.id = client_service_prices.client_id
      and c.owner_id = (select auth.uid())
  )
  and exists (
    select 1 from public.services s
    where s.id = client_service_prices.service_id
      and s.owner_id = (select auth.uid())
  )
);

create index if not exists client_service_prices_client_id_idx
  on public.client_service_prices(client_id);

create index if not exists client_service_prices_service_id_idx
  on public.client_service_prices(service_id);

alter table public.appointments
  add column if not exists list_price integer;
