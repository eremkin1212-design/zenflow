-- RITENA certificates and subscriptions.
-- Certificates can hold a monetary balance, one service, or several sessions.

create sequence if not exists public.certificate_number_seq start 1;

create table if not exists public.certificates (
  id bigint generated by default as identity primary key,
  owner_id uuid not null default auth.uid() references auth.users(id) on delete cascade,
  number text not null default ('RT-' || lpad(nextval('public.certificate_number_seq')::text, 6, '0')),
  kind text not null check (kind in ('amount','service','sessions')),
  client_id bigint references public.clients(id) on delete set null,
  service_id bigint references public.services(id) on delete set null,
  initial_amount integer not null default 0 check (initial_amount >= 0),
  remaining_amount integer not null default 0 check (remaining_amount >= 0),
  initial_sessions integer not null default 0 check (initial_sessions >= 0),
  remaining_sessions integer not null default 0 check (remaining_sessions >= 0),
  expires_at date,
  note text,
  status text not null default 'active' check (status in ('active','used','cancelled')),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  unique (owner_id, number),
  check (
    (kind = 'amount' and initial_amount > 0 and initial_sessions = 0)
    or
    (kind in ('service','sessions') and service_id is not null and initial_sessions > 0 and initial_amount = 0)
  )
);

create table if not exists public.certificate_redemptions (
  id bigint generated by default as identity primary key,
  owner_id uuid not null default auth.uid() references auth.users(id) on delete cascade,
  certificate_id bigint not null references public.certificates(id) on delete cascade,
  appointment_id bigint not null references public.appointments(id) on delete cascade,
  amount_used integer not null default 0 check (amount_used >= 0),
  sessions_used integer not null default 0 check (sessions_used >= 0),
  topup_amount integer not null default 0 check (topup_amount >= 0),
  topup_method text,
  created_at timestamptz not null default now(),
  unique (certificate_id, appointment_id)
);

alter table public.certificates enable row level security;
alter table public.certificate_redemptions enable row level security;

revoke all on table public.certificates from anon;
revoke all on table public.certificate_redemptions from anon;
grant select, insert, update, delete on table public.certificates to authenticated;
grant select, insert on table public.certificate_redemptions to authenticated;
grant usage, select on sequence public.certificates_id_seq to authenticated;
grant usage, select on sequence public.certificate_redemptions_id_seq to authenticated;
grant usage, select on sequence public.certificate_number_seq to authenticated;

drop policy if exists "own certificates" on public.certificates;
create policy "own certificates"
on public.certificates
for all
to authenticated
using (
  owner_id = (select auth.uid())
  and (client_id is null or exists (
    select 1 from public.clients c
    where c.id = certificates.client_id and c.owner_id = (select auth.uid())
  ))
  and (service_id is null or exists (
    select 1 from public.services s
    where s.id = certificates.service_id and s.owner_id = (select auth.uid())
  ))
)
with check (
  owner_id = (select auth.uid())
  and (client_id is null or exists (
    select 1 from public.clients c
    where c.id = certificates.client_id and c.owner_id = (select auth.uid())
  ))
  and (service_id is null or exists (
    select 1 from public.services s
    where s.id = certificates.service_id and s.owner_id = (select auth.uid())
  ))
);

drop policy if exists "own certificate redemptions" on public.certificate_redemptions;
create policy "own certificate redemptions"
on public.certificate_redemptions
for select
to authenticated
using (
  owner_id = (select auth.uid())
  and exists (
    select 1 from public.certificates c
    where c.id = certificate_redemptions.certificate_id and c.owner_id = (select auth.uid())
  )
  and exists (
    select 1 from public.appointments a
    where a.id = certificate_redemptions.appointment_id and a.owner_id = (select auth.uid())
  )
);

drop policy if exists "insert own certificate redemptions" on public.certificate_redemptions;
create policy "insert own certificate redemptions"
on public.certificate_redemptions
for insert
to authenticated
with check (
  owner_id = (select auth.uid())
  and exists (
    select 1 from public.certificates c
    where c.id = certificate_redemptions.certificate_id and c.owner_id = (select auth.uid())
  )
  and exists (
    select 1 from public.appointments a
    where a.id = certificate_redemptions.appointment_id and a.owner_id = (select auth.uid())
  )
);

create index if not exists certificates_owner_status_idx on public.certificates(owner_id,status);
create index if not exists certificates_owner_number_idx on public.certificates(owner_id,number);
create index if not exists certificate_redemptions_certificate_idx on public.certificate_redemptions(certificate_id);

create or replace function public.redeem_certificate_for_appointment(
  p_certificate_number text,
  p_appointment_id bigint,
  p_service_total integer,
  p_topup_method text default null
)
returns jsonb
language plpgsql
security invoker
set search_path = public, pg_temp
as $$
declare
  v_cert public.certificates%rowtype;
  v_appointment public.appointments%rowtype;
  v_payment_id bigint;
  v_service_count integer := 0;
  v_service_id bigint;
  v_amount_used integer := 0;
  v_sessions_used integer := 0;
  v_due integer := 0;
  v_remaining_amount integer := 0;
  v_remaining_sessions integer := 0;
  v_new_status text := 'active';
  v_method_label text;
  v_today text := to_char(timezone('Asia/Novosibirsk', now()), 'YYYY-MM-DD');
begin
  if p_service_total is null or p_service_total < 0 then
    raise exception 'Некорректная стоимость услуги';
  end if;

  select a.* into v_appointment
  from public.appointments a
  where a.id = p_appointment_id and a.owner_id = (select auth.uid())
  for update;
  if not found then raise exception 'Запись не найдена'; end if;

  select cp.id into v_payment_id
  from public.client_payments cp
  where cp.appointment_id = p_appointment_id
  order by cp.id desc limit 1;
  if v_payment_id is not null then
    return jsonb_build_object('already_paid', true, 'appointment_id', p_appointment_id);
  end if;

  select c.* into v_cert
  from public.certificates c
  where c.owner_id = (select auth.uid())
    and upper(c.number) = upper(trim(p_certificate_number))
  for update;
  if not found then raise exception 'Сертификат не найден'; end if;

  if v_cert.status <> 'active' then raise exception 'Сертификат уже использован или отменён'; end if;
  if v_cert.expires_at is not null and v_cert.expires_at < current_date then raise exception 'Срок действия сертификата истёк'; end if;
  if v_cert.client_id is not null and v_cert.client_id <> v_appointment.client_id then raise exception 'Сертификат привязан к другому клиенту'; end if;

  select count(*), max(aps.service_id)
    into v_service_count, v_service_id
  from public.appointment_services aps
  where aps.appointment_id = p_appointment_id;

  if v_service_count = 0 then
    v_service_count := case when v_appointment.service_id is null then 0 else 1 end;
    v_service_id := v_appointment.service_id;
  end if;

  if v_cert.kind = 'amount' then
    if v_cert.remaining_amount <= 0 then raise exception 'На сертификате нет остатка'; end if;
    v_amount_used := least(v_cert.remaining_amount, p_service_total);
    v_due := p_service_total - v_amount_used;
    v_remaining_amount := v_cert.remaining_amount - v_amount_used;
    v_remaining_sessions := v_cert.remaining_sessions;
    if v_remaining_amount = 0 then v_new_status := 'used'; end if;
  else
    if v_service_count <> 1 or v_service_id is null then raise exception 'Сертификат на услугу можно применить только к записи с одной услугой'; end if;
    if v_cert.service_id <> v_service_id then raise exception 'Этот сертификат предназначен для другой услуги'; end if;
    if v_cert.remaining_sessions <= 0 then raise exception 'На сертификате не осталось сеансов'; end if;
    v_sessions_used := 1;
    v_amount_used := p_service_total;
    v_due := 0;
    v_remaining_amount := v_cert.remaining_amount;
    v_remaining_sessions := v_cert.remaining_sessions - 1;
    if v_remaining_sessions = 0 then v_new_status := 'used'; end if;
  end if;

  if v_due > 0 and coalesce(p_topup_method,'') not in ('Наличные','Карта') then
    raise exception 'Нужно выбрать способ доплаты';
  end if;

  update public.certificates
  set remaining_amount = v_remaining_amount,
      remaining_sessions = v_remaining_sessions,
      status = v_new_status,
      updated_at = now()
  where id = v_cert.id;

  insert into public.certificate_redemptions(
    owner_id,certificate_id,appointment_id,amount_used,sessions_used,topup_amount,topup_method
  ) values (
    (select auth.uid()),v_cert.id,p_appointment_id,v_amount_used,v_sessions_used,v_due,
    case when v_due > 0 then p_topup_method else null end
  );

  update public.appointments
  set status='done',price=p_service_total,full_price=p_service_total
  where id=p_appointment_id;

  v_method_label := case
    when v_cert.kind='amount' and v_due>0 then format('Сертификат %s %s ₽ + %s %s ₽',v_cert.number,v_amount_used,p_topup_method,v_due)
    when v_cert.kind='amount' then format('Сертификат %s %s ₽',v_cert.number,v_amount_used)
    else format('Сертификат %s · 1 сеанс',v_cert.number)
  end;

  insert into public.client_payments(client_id,appointment_id,amount,discount_percent,method,date)
  values (v_appointment.client_id,p_appointment_id,p_service_total,0,v_method_label,v_today);

  return jsonb_build_object(
    'already_paid',false,
    'appointment_id',p_appointment_id,
    'certificate_id',v_cert.id,
    'certificate_number',v_cert.number,
    'kind',v_cert.kind,
    'amount_used',v_amount_used,
    'sessions_used',v_sessions_used,
    'topup_amount',v_due,
    'remaining_amount',v_remaining_amount,
    'remaining_sessions',v_remaining_sessions,
    'status',v_new_status
  );
end;
$$;

revoke all on function public.redeem_certificate_for_appointment(text,bigint,integer,text) from public,anon;
grant execute on function public.redeem_certificate_for_appointment(text,bigint,integer,text) to authenticated;
